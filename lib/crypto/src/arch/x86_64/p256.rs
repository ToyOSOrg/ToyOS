//! P-256 field multiplication and squaring on BMI2 and ADX, in registers:
//! the whole product, then P-256's reduction step (`montgomery`'s
//! `Form::P256`) in place. Product rows add low halves on CF through `adcx`
//! and high halves on OF through `adox` (Intel SDM Vol. 2A, ADCX, ADOX and
//! MULX). No branch or address depends on the operands.

use core::arch::asm;

/// p's top word; its other words enter the reduction step as shifts.
const P3: u64 = 0xffff_ffff_0000_0001;

/// a b / 2^256 mod p for a, b < p: the whole product first, each row's low
/// halves added on CF (`adcx`) and its high halves on OF (`adox`), then
/// [`square`]'s reduction. A product row needs only the operands, so the
/// rows overlap where CIOS's reduction steps would chain them.
///
/// # Safety
/// The CPU has BMI2 and ADX.
#[inline]
pub(super) unsafe fn mul(a: &[u64; 4], b: &[u64; 4]) -> [u64; 4] {
    let (r0, r1, r2, r3): (u64, u64, u64, u64);
    // SAFETY: the template reads the four words of `a` and of `b`, writes
    // only its declared registers and leaves the stack alone.
    unsafe {
        asm!(
            "mov rdx, [{a}]",
            "mulx {T1}, {T0}, [{b}]",
            "mulx {T2}, {lo}, [{b} + 8]",
            "add {T1}, {lo}",
            "mulx {T3}, {lo}, [{b} + 16]",
            "adc {T2}, {lo}",
            "mulx {T4}, {lo}, [{b} + 24]",
            "adc {T3}, {lo}",
            "adc {T4}, 0",
            "mov rdx, [{a} + 8]",
            "xor {T5:e}, {T5:e}",
            "mulx {hi}, {lo}, [{b}]",
            "adcx {T1}, {lo}",
            "adox {T2}, {hi}",
            "mulx {hi}, {lo}, [{b} + 8]",
            "adcx {T2}, {lo}",
            "adox {T3}, {hi}",
            "mulx {hi}, {lo}, [{b} + 16]",
            "adcx {T3}, {lo}",
            "adox {T4}, {hi}",
            "mulx {hi}, {lo}, [{b} + 24]",
            "adcx {T4}, {lo}",
            "adox {T5}, {hi}",
            "adc {T5}, 0",
            "mov rdx, [{a} + 16]",
            "xor {T6:e}, {T6:e}",
            "mulx {hi}, {lo}, [{b}]",
            "adcx {T2}, {lo}",
            "adox {T3}, {hi}",
            "mulx {hi}, {lo}, [{b} + 8]",
            "adcx {T3}, {lo}",
            "adox {T4}, {hi}",
            "mulx {hi}, {lo}, [{b} + 16]",
            "adcx {T4}, {lo}",
            "adox {T5}, {hi}",
            "mulx {hi}, {lo}, [{b} + 24]",
            "adcx {T5}, {lo}",
            "adox {T6}, {hi}",
            "adc {T6}, 0",
            "mov rdx, [{a} + 24]",
            "xor {T7:e}, {T7:e}",
            "mulx {hi}, {lo}, [{b}]",
            "adcx {T3}, {lo}",
            "adox {T4}, {hi}",
            "mulx {hi}, {lo}, [{b} + 8]",
            "adcx {T4}, {lo}",
            "adox {T5}, {hi}",
            "mulx {hi}, {lo}, [{b} + 16]",
            "adcx {T5}, {lo}",
            "adox {T6}, {hi}",
            "mulx {hi}, {lo}, [{b} + 24]",
            "adcx {T6}, {lo}",
            "adox {T7}, {hi}",
            "adc {T7}, 0",
            "mov {b}, {p3}",
            "mov rdx, {T0}",
            "mulx {hi}, {lo}, {b}",
            "shl rdx, 32",
            "shr {T0}, 32",
            "add {T1}, rdx",
            "adc {T2}, {T0}",
            "adc {T3}, {lo}",
            "adc {T4}, {hi}",
            "adc {T5}, 0",
            "adc {T6}, 0",
            "adc {T7}, 0",
            "mov {T0:e}, 0",
            "adc {T0}, 0",
            "mov rdx, {T1}",
            "mulx {hi}, {lo}, {b}",
            "shl rdx, 32",
            "shr {T1}, 32",
            "add {T2}, rdx",
            "adc {T3}, {T1}",
            "adc {T4}, {lo}",
            "adc {T5}, {hi}",
            "adc {T6}, 0",
            "adc {T7}, 0",
            "adc {T0}, 0",
            "mov rdx, {T2}",
            "mulx {hi}, {lo}, {b}",
            "shl rdx, 32",
            "shr {T2}, 32",
            "add {T3}, rdx",
            "adc {T4}, {T2}",
            "adc {T5}, {lo}",
            "adc {T6}, {hi}",
            "adc {T7}, 0",
            "adc {T0}, 0",
            "mov rdx, {T3}",
            "mulx {hi}, {lo}, {b}",
            "shl rdx, 32",
            "shr {T3}, 32",
            "add {T4}, rdx",
            "adc {T5}, {T3}",
            "adc {T6}, {lo}",
            "adc {T7}, {hi}",
            "adc {T0}, 0",
            "mov {T1}, {T4}",
            "mov {T2}, {T5}",
            "mov {T3}, {T6}",
            "mov rdx, {T7}",
            "mov {lo:e}, 0xffffffff",
            "sub {T1}, -1",
            "sbb {T2}, {lo}",
            "sbb {T3}, 0",
            "sbb rdx, {b}",
            "sbb {T0}, 0",
            "cmovnc {T4}, {T1}",
            "cmovnc {T5}, {T2}",
            "cmovnc {T6}, {T3}",
            "cmovnc {T7}, rdx",
            a = in(reg) a.as_ptr(),
            b = inout(reg) b.as_ptr() => _,
            p3 = const P3,
            T0 = out(reg) _,
            T1 = out(reg) _,
            T2 = out(reg) _,
            T3 = out(reg) _,
            T4 = out(reg) r0,
            T5 = out(reg) r1,
            T6 = out(reg) r2,
            T7 = out(reg) r3,
            lo = out(reg) _,
            hi = out(reg) _,
            out("rdx") _,
            options(pure, readonly, nostack),
        );
    }
    [r0, r1, r2, r3]
}

/// a^2 / 2^256 mod p for a < p: the six cross products once, doubled, the
/// four squares added, then four reduction steps in place, each with q the
/// lowest word left and its carry rippled into the words above; the word
/// each step clears holds the bit that carries out of the top. The sum is
/// below 2p, and p is subtracted where that does not borrow, by `cmov`.
///
/// # Safety
/// The CPU has BMI2 and ADX.
#[inline]
pub(super) unsafe fn square(a: &[u64; 4]) -> [u64; 4] {
    let (r0, r1, r2, r3): (u64, u64, u64, u64);
    // SAFETY: the template reads the four words of `a`, writes only its
    // declared registers and leaves the stack alone.
    unsafe {
        asm!(
            // Cross products into (T1 .. T6).
            "mov rdx, [{a}]",
            "mulx {T2}, {T1}, [{a} + 8]",
            "mulx {T3}, {lo}, [{a} + 16]",
            "add {T2}, {lo}",
            "mulx {T4}, {lo}, [{a} + 24]",
            "adc {T3}, {lo}",
            "adc {T4}, 0",
            "mov rdx, [{a} + 8]",
            "mulx {hi}, {lo}, [{a} + 16]",
            "add {T3}, {lo}",
            "adc {T4}, {hi}",
            "mulx {T5}, {lo}, [{a} + 24]",
            "adc {T5}, 0",
            "add {T4}, {lo}",
            "adc {T5}, 0",
            "mov rdx, [{a} + 16]",
            "mulx {T6}, {lo}, [{a} + 24]",
            "add {T5}, {lo}",
            "adc {T6}, 0",
            // Doubled into (T1 .. T7).
            "xor {T7:e}, {T7:e}",
            "add {T1}, {T1}",
            "adc {T2}, {T2}",
            "adc {T3}, {T3}",
            "adc {T4}, {T4}",
            "adc {T5}, {T5}",
            "adc {T6}, {T6}",
            "adc {T7}, 0",
            // The squares added into (T0 .. T7).
            "mov rdx, [{a}]",
            "mulx {hi}, {T0}, rdx",
            "add {T1}, {hi}",
            "mov rdx, [{a} + 8]",
            "mulx {hi}, {lo}, rdx",
            "adc {T2}, {lo}",
            "adc {T3}, {hi}",
            "mov rdx, [{a} + 16]",
            "mulx {hi}, {lo}, rdx",
            "adc {T4}, {lo}",
            "adc {T5}, {hi}",
            "mov rdx, [{a} + 24]",
            "mulx {hi}, {lo}, rdx",
            "adc {T6}, {lo}",
            "adc {T7}, {hi}",
            // Reduction steps; T0 then gathers the carry out of T7.
            "mov {a}, {p3}",
            "mov rdx, {T0}",
            "mulx {hi}, {lo}, {a}",
            "shl rdx, 32",
            "shr {T0}, 32",
            "add {T1}, rdx",
            "adc {T2}, {T0}",
            "adc {T3}, {lo}",
            "adc {T4}, {hi}",
            "adc {T5}, 0",
            "adc {T6}, 0",
            "adc {T7}, 0",
            "mov {T0:e}, 0",
            "adc {T0}, 0",
            "mov rdx, {T1}",
            "mulx {hi}, {lo}, {a}",
            "shl rdx, 32",
            "shr {T1}, 32",
            "add {T2}, rdx",
            "adc {T3}, {T1}",
            "adc {T4}, {lo}",
            "adc {T5}, {hi}",
            "adc {T6}, 0",
            "adc {T7}, 0",
            "adc {T0}, 0",
            "mov rdx, {T2}",
            "mulx {hi}, {lo}, {a}",
            "shl rdx, 32",
            "shr {T2}, 32",
            "add {T3}, rdx",
            "adc {T4}, {T2}",
            "adc {T5}, {lo}",
            "adc {T6}, {hi}",
            "adc {T7}, 0",
            "adc {T0}, 0",
            "mov rdx, {T3}",
            "mulx {hi}, {lo}, {a}",
            "shl rdx, 32",
            "shr {T3}, 32",
            "add {T4}, rdx",
            "adc {T5}, {T3}",
            "adc {T6}, {lo}",
            "adc {T7}, {hi}",
            "adc {T0}, 0",
            // (T4 .. T7 T0) - p, as in `mul`.
            "mov {T1}, {T4}",
            "mov {T2}, {T5}",
            "mov {T3}, {T6}",
            "mov rdx, {T7}",
            "mov {lo:e}, 0xffffffff",
            "sub {T1}, -1",
            "sbb {T2}, {lo}",
            "sbb {T3}, 0",
            "sbb rdx, {a}",
            "sbb {T0}, 0",
            "cmovnc {T4}, {T1}",
            "cmovnc {T5}, {T2}",
            "cmovnc {T6}, {T3}",
            "cmovnc {T7}, rdx",
            a = inout(reg) a.as_ptr() => _,
            p3 = const P3,
            T0 = out(reg) _,
            T1 = out(reg) _,
            T2 = out(reg) _,
            T3 = out(reg) _,
            T4 = out(reg) r0,
            T5 = out(reg) r1,
            T6 = out(reg) r2,
            T7 = out(reg) r3,
            lo = out(reg) _,
            hi = out(reg) _,
            out("rdx") _,
            options(pure, readonly, nostack),
        );
    }
    [r0, r1, r2, r3]
}
