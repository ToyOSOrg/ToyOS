//! What `strerror` says of each code `include/errno.h` defines, by number:
//! POSIX's own description of the code where it gives one (IEEE Std
//! 1003.1-2017, `<errno.h>`), worded here where it gives none, as for the
//! codes it reserves. It reads nothing but what it is handed, so the host
//! tests it (`toyos-libc-copies`).

